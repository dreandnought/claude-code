/**
 * Build single-file, standalone executables for every supported platform.
 *
 * Each output is a self-contained binary — no Node.js, no Bun, no node_modules
 * and no sidecar `vendor/` directory required at runtime:
 *
 *   1. bake the target platform's ripgrep into src/utils/vendor/embeddedRg.ts
 *      (base64), so the binary can extract it on first Grep/Glob call;
 *   2. run the normal `build.ts` bundle so `feature()` flags, vendor copies and
 *      the import.meta.require patch are applied exactly as in a release build;
 *   3. `bun build --compile` the resulting dist/cli.js for the target platform.
 *
 * Usage: bun run scripts/build-binaries.ts [target ...]
 *        targets: linux-x64 linux-arm64 win32-x64 darwin-arm64 darwin-x64
 */
import { readFileSync, writeFileSync, rmSync, mkdirSync, statSync } from 'fs'
import { createHash } from 'crypto'
import { join } from 'path'

const ROOT = join(import.meta.dir, '..')
// The vendored ripgrep binaries may live in this repo's node_modules, in a
// sibling checkout, or in the bun install cache — take whichever exists first.
const RG_ROOT_CANDIDATES = [
  join(ROOT, 'node_modules/@anthropic-ai/claude-agent-sdk/vendor/ripgrep'),
  join(
    ROOT,
    '../../claude-code-rev/node_modules/@anthropic-ai/claude-agent-sdk/vendor/ripgrep',
  ),
  join(ROOT, 'src/utils/vendor/ripgrep'),
]

function findRgRoot(): string {
  for (const candidate of RG_ROOT_CANDIDATES) {
    try {
      if (statSync(candidate).isDirectory()) return candidate
    } catch {}
  }
  throw new Error(
    `No vendored ripgrep found. Looked in:\n  ${RG_ROOT_CANDIDATES.join('\n  ')}`,
  )
}
const STUB = join(ROOT, 'src/utils/vendor/embeddedRg.ts')
// NB: build.ts wipes dist/ on every run, so artifacts must live outside it.
const OUT_DIR = join(ROOT, 'release')

type Target = {
  /** `${process.platform}-${process.arch}` of the *runtime* platform */
  platformKey: string
  /** vendor dir name under RG_ROOT */
  rgDir: string
  rgFile: string
  /** bun --compile target */
  bunTarget: string
  outfile: string
}

const TARGETS: Target[] = [
  {
    platformKey: 'linux-x64',
    rgDir: 'x64-linux',
    rgFile: 'rg',
    bunTarget: 'bun-linux-x64',
    outfile: 'ccb-linux-x64',
  },
  {
    platformKey: 'linux-arm64',
    rgDir: 'arm64-linux',
    rgFile: 'rg',
    bunTarget: 'bun-linux-arm64',
    outfile: 'ccb-linux-arm64',
  },
  {
    platformKey: 'win32-x64',
    rgDir: 'x64-win32',
    rgFile: 'rg.exe',
    bunTarget: 'bun-windows-x64',
    outfile: 'ccb-windows-x64.exe',
  },
  {
    platformKey: 'darwin-arm64',
    rgDir: 'arm64-darwin',
    rgFile: 'rg',
    bunTarget: 'bun-darwin-arm64',
    outfile: 'ccb-macos-arm64',
  },
  {
    platformKey: 'darwin-x64',
    rgDir: 'x64-darwin',
    rgFile: 'rg',
    bunTarget: 'bun-darwin-x64',
    outfile: 'ccb-macos-x64',
  },
]

const STUB_CONTENT = readFileSync(STUB, 'utf-8')

function run(cmd: string[], label: string): void {
  const proc = Bun.spawnSync(cmd, {
    cwd: ROOT,
    stdout: 'inherit',
    stderr: 'inherit',
  })
  if (proc.exitCode !== 0) {
    throw new Error(`${label} failed with exit code ${proc.exitCode}`)
  }
}

function bakeRipgrep(target: Target): void {
  const rgPath = join(findRgRoot(), target.rgDir, target.rgFile)
  const bytes = readFileSync(rgPath)
  const b64 = bytes.toString('base64')
  writeFileSync(
    STUB,
    `// AUTO-GENERATED by scripts/build-binaries.ts — restored after the build.\n` +
      `export const EMBEDDED_RG_PLATFORM: string = ${JSON.stringify(target.platformKey)}\n` +
      `export const EMBEDDED_RG_BASE64: string = '${b64}'\n`,
  )
  console.log(
    `  baked ripgrep ${target.rgDir}/${target.rgFile} (${(bytes.length / 1e6).toFixed(1)} MB → ${(b64.length / 1e6).toFixed(1)} MB base64)`,
  )
}

function sha256(file: string): string {
  return createHash('sha256').update(readFileSync(file)).digest('hex')
}

const requested = process.argv.slice(2)
const selected = requested.length
  ? TARGETS.filter(
      t => requested.includes(t.platformKey) || requested.includes(t.outfile),
    )
  : TARGETS

if (selected.length === 0) {
  console.error(
    `No matching targets. Known: ${TARGETS.map(t => t.platformKey).join(', ')}`,
  )
  process.exit(1)
}

mkdirSync(OUT_DIR, { recursive: true })

const results: string[] = []
try {
  for (const target of selected) {
    console.log(`\n=== ${target.outfile} (${target.bunTarget}) ===`)
    bakeRipgrep(target)

    run(['bun', 'run', 'build.ts'], 'bundle')

    const outfile = join(OUT_DIR, target.outfile)
    rmSync(outfile, { force: true })
    run(
      [
        'bun',
        'build',
        'dist/cli.js',
        '--compile',
        '--minify',
        `--target=${target.bunTarget}`,
        `--outfile=${outfile}`,
        '--no-compile-autoload-dotenv',
        '--no-compile-autoload-bunfig',
        '--no-compile-autoload-tsconfig',
        '--no-compile-autoload-package-json',
      ],
      'compile',
    )

    const size = statSync(outfile).size
    results.push(
      `${target.outfile}\t${(size / 1048576).toFixed(1)} MB\tsha256=${sha256(outfile)}`,
    )
  }
} finally {
  writeFileSync(STUB, STUB_CONTENT)
  console.log('\nrestored embeddedRg.ts stub')
}

console.log('\n=== artifacts ===')
for (const line of results) console.log(line)
